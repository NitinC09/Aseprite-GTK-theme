#!/usr/bin/env python3
"""Build the dark (Slate) variant from the light theme.

Generates, from the light files:
  gtk-4.0/gtk-dark.css   + gtk-4.0/assets/dark/
  gtk-3.0/gtk-dark.css   + gtk-3.0/assets/dark/
and the generated check/radio block inside gtk-4.0/gtk.css (data: images).

Dark images live in assets/dark/ (not a sibling folder) because nwg-look
links only gtk.css, gtk-dark.css and assets/ into ~/.config/gtk-4.0, and
GTK resolves image paths relative to that folder.

Edit the light theme, then re-run this script to keep dark in sync:
    python3 tools/build_dark.py          (needs Pillow for the images)

How the dark theme is switched on is explained in the README:
GTK 4 follows the desktop colour scheme through the @media block at the end
of gtk-4.0/gtk.css, GTK 3 loads gtk-dark.css when
gtk-application-prefer-dark-theme is set.
"""
