DARK_IMPORT_RE = re.compile(r"\n*/\* ={5,}\n \* Dark mode.*?@media \(prefers-color-scheme: dark\) \{.*?\}\n", re.S)


def build_gtk4():
    src = os.path.join(ROOT, "gtk-4.0", "gtk.css")
    css = open(src).read()
    css = DARK_IMPORT_RE.sub("\n", css)          # no self-import in the dark file
    for name, role in GTK4_DEFS.items():
        css, n = re.subn(r"(@define-color %s\s+)[^;]+;" % re.escape(name),
                         r"\g<1>%s;" % P[role], css)
        assert n == 1, name
    css = css.replace('url("assets/', 'url("assets/dark/')
    head = ("/* GENERATED by tools/build_dark.py from gtk.css: do not edit by hand.\n"
            " * Aseprite, dark variant (Slate). */\n")
    open(os.path.join(ROOT, "gtk-4.0", "gtk-dark.css"), "w").write(head + css)


# ---- GTK 3: property-aware colour mapping --------------------------------
def _rgba(hexcol, a):
    h = hexcol.lstrip("#")
    return "rgba(%d, %d, %d, %s)" % (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


def gtk3_map(col, kind):
    """kind: text | bg | border | shadow"""
    c = col.lower()
    if c in ("#000", "#000000", "black"):
        return P["fg"] if kind == "text" else col
    if c in ("#fff", "#ffffff", "white"):
        if kind == "text":
            return col
        return P["base"] if kind == "bg" else P["hi"]
    table = {
        "#e7dcc5": P["bg"], "#d7d0c2": P["face"], "#7c7c7c": P["lo"], "#d8caae": P["panel"],
        "#7c919d": P["blue"] if kind != "text" else P["blue_hi"],
        "#adcade": P["blue_hi"], "#645460": P["blue_lo"], "#786050": P["focus"],
        "#9e896d": P["dis_fg"] if kind == "text" else P["bg_dark"],
        "#fffcf5": P["base"],
        "#b6b6b6": P["dis_bg"], "#606060": P["dis_fg"], "#0a0a0a": P["dis_fg"],
        "#a4a4a4": P["dis_bg"], "#adadad": P["face_hover"], "#9b9b9b": P["lo"],
        "#e6e6e6": P["dis_bg"], "#4b4d4c": P["fg"] if kind == "text" else P["face"],
        "#737373": P["dis_fg"], "#6c6c6c": P["lo"], "#b2b2b2": P["lo"],
        "#ffff7d": P["tip"], "#ffff74": P["tip"], "#1d72e9": P["link"],
        "#175bba": P["link_visited"], "#2c7ff4": P["link"],
        "#c8603a": P["sel"],
    }
    if kind == "text" and c == "#303030":
        return P["dis_fg"]
    if c in table:
        return table[c]
    m = re.match(r"rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)", c)
    if m:
        r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
        if (r, g, b) == (0, 0, 0) and kind == "text":
            return _rgba(P["fg"], m[4])
        if (r, g, b) == (255, 255, 255) and kind != "text":
            return "rgba(255, 255, 255, %g)" % round(a * 0.3, 3)
        if (r, g, b) == (173, 202, 222):
            return _rgba(P["blue_hi"], round(a * 0.8, 3))
    return col


COLOR_RE = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|\bwhite\b|\bblack\b|rgba\([^)]*\)")
DECL_RE = re.compile(r"(?<![@\w-])([-a-zA-Z]+)(\s*:\s*)([^;{}]+)")


def build_gtk3():
    src = os.path.join(ROOT, "gtk-3.0", "gtk.css")
    css = open(src).read()
    out = []
    for line in css.split("\n"):
        if line.lstrip().startswith("@define-color"):
            out.append(line)
            continue
        def decl(m):
            prop, sep, val = m.group(1), m.group(2), m.group(3)
            if "url(" in val or prop.startswith("-gtk-icon"):
                return m.group(0)
            kind = ("text" if prop in ("color", "caret-color") else
                    "bg" if prop.startswith("background") else
                    "shadow" if "shadow" in prop else "border")
            return prop + sep + COLOR_RE.sub(lambda c: gtk3_map(c.group(0), kind), val)
        out.append(DECL_RE.sub(decl, line))
    css = "\n".join(out)
    named = {"theme_fg_color": "fg", "theme_text_color": "fg", "theme_bg_color": "bg",
             "theme_base_color": "base", "theme_selected_bg_color": "sel",
             "theme_selected_fg_color": "sel_fg", "insensitive_bg_color": "dis_bg",
             "insensitive_fg_color": "dis_fg", "insensitive_base_color": "dis_bg",
             "theme_unfocused_fg_color": "fg", "theme_unfocused_text_color": "fg",
             "theme_unfocused_bg_color": "bg", "theme_unfocused_base_color": "base",
             "theme_unfocused_selected_bg_color": "sel",
             "theme_unfocused_selected_fg_color": "sel_fg",
             "unfocused_insensitive_color": "dis_fg", "content_view_bg": "base"}
    for name, role in named.items():
        css = re.sub(r"(@define-color %s\s+)[^;]+;" % name, r"\g<1>%s;" % P[role], css)
    css = css.replace('url("assets/', 'url("assets/dark/')
    head = ("/* GENERATED by tools/build_dark.py from gtk.css: do not edit by hand.\n"
            "   Aseprite, dark variant (Slate). */\n")
    open(os.path.join(ROOT, "gtk-3.0", "gtk-dark.css"), "w").write(head + css)


# ---- images ----------------------------------------------------------------
def _hex(c):
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))


def _lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def grey_curve(v, stops):
    """Map a light-theme grey level onto the dark ramp, keeping black black."""
    for (v0, c0), (v1, c1) in zip(stops, stops[1:]):
        if v0 <= v <= v1:
            return _lerp(_hex(c0), _hex(c1), (v - v0) / ((v1 - v0) or 1))
    return _hex(stops[-1][1])


TOGGLE_OUTLINE = "#d0d4da"        # check/radio outline in dark: bright, like black is in light
TOGGLE_OUTLINE_OFF = "#6b737d"    # same, for insensitive (greyed-out) controls


def _fill_inside(im, rgb):
    """Fill transparent pixels that are enclosed by the drawing (not reachable
    from the image edge), so an unchecked box gets a solid interior."""
    w, h = im.size
    px = im.load()
    outside = set()
    stack = [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
    while stack:
        x, y = stack.pop()
        if (x, y) in outside or not (0 <= x < w and 0 <= y < h) or px[x, y][3] != 0:
            continue
        outside.add((x, y))
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    for y in range(h):
        for x in range(w):
            if px[x, y][3] == 0 and (x, y) not in outside:
                px[x, y] = rgb + (255,)


def recolor_png(src, dst, light_ramp=False, toggle=None, insensitive=False):
    """light_ramp: small controls drawn on the window background (check and
    radio buttons, title buttons). Their light-theme outlines are *shadow*
    colours, darker than the background, which would vanish on a dark
    background, so they get a lighter ramp and a visible outline."""
    from PIL import Image
    face, hi, lo = (("#8a929c", "#b4bcc6", "#5a626b") if light_ramp
                    else (P["face"], P["hi"], P["lo"]))
    stops = [(0, "#000000"), (124, lo), (198, face), (255, hi)]
    exact = {(0xd7, 0xd0, 0xc2): _hex(P["face"]), (0x9e, 0x89, 0x6d): _hex(P["bg_dark"]), (0xe7, 0xdc, 0xc5): _hex(P["bg"]),
             (0x64, 0x54, 0x60): _hex(P["blue_lo"]), (0xad, 0xca, 0xde): _hex(P["title_hi"]),
             (0x78, 0x60, 0x50): _hex(P["focus"]), (0x55, 0x64, 0x6c): (0x34, 0x44, 0x4e)}
    if light_ramp:
        exact[(0x9e, 0x89, 0x6d)] = _hex("#8a929c")   # brown outline -> light grey
        exact[(0xd7, 0xd0, 0xc2)] = _hex("#8a929c")   # warm face -> light-ramp face
        exact[(0x64, 0x54, 0x60)] = _hex("#5a626b")   # plum shade -> mid grey
    outline = _hex(TOGGLE_OUTLINE_OFF if insensitive else TOGGLE_OUTLINE)
    if toggle == "check":                             # brown frame -> bright frame
        exact[(0x9e, 0x89, 0x6d)] = outline
        exact[(0x7c, 0x7c, 0x7c)] = outline if insensitive else _hex("#5a626b")
    elif toggle == "radio":                           # black ring -> bright ring
        exact[(0x00, 0x00, 0x00)] = outline
        exact[(0xe7, 0xdc, 0xc5)] = _hex(P["base"])   # beige inside -> content shade
    im = Image.open(src).convert("RGBA")
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            if (r, g, b) in exact:
                px[x, y] = exact[(r, g, b)] + (a,)
            elif abs(r - g) < 8 and abs(g - b) < 8:
                px[x, y] = grey_curve((r + g + b) // 3, stops) + (a,)
    if toggle:
        _fill_inside(im, _hex(P["base"]))
    im.save(dst)


def recolor_svg(src, dst):
    face, hi, lo = "#8a929c", "#b4bcc6", "#5a626b"
    m = {"#ffffff": hi, "#c6c6c6": face, "#7c7c7c": lo, "#645460": P["blue_lo"],
         "#adcade": P["title_hi"], "#55646c": "#34444e"}
    s = open(src).read()
    for k, v in m.items():
        s = re.sub(re.escape(k), v, s, flags=re.I)
    open(dst, "w").write(s)


def build_assets(gtkdir):
    src = os.path.join(ROOT, gtkdir, "assets")
    dst = os.path.join(src, "dark")
    shutil.rmtree(dst, ignore_errors=True)
    shutil.rmtree(os.path.join(ROOT, gtkdir, "assets-dark"), ignore_errors=True)  # old location
    os.makedirs(dst)
    for f in sorted(os.listdir(src)):
        if os.path.isdir(os.path.join(src, f)):
            continue
        a, b = os.path.join(src, f), os.path.join(dst, f)
        if f.endswith(".png"):
            base = f.split(".")[0].split("@")[0]
            toggle = "check" if base.startswith("checkbox") else "radio" if base.startswith("radio") else None
            recolor_png(a, b, light_ramp=base in ("close", "maximize", "minimize", "restore") or bool(toggle),
                        toggle=toggle, insensitive=("insensitive" in base or "disabled" in base))
        elif f.endswith(".svg") and f.startswith("titlebutton"):
            recolor_svg(a, b)
        else:
            shutil.copy(a, b)


TOGGLES_RE = re.compile(r"(/\* BEGIN generated: check and radio images[^\n]*\*/\n).*?(/\* END generated \*/)", re.S)


def toggles_css(folder):
    """The check/radio rules from tools/toggles.template.css with every image
    embedded as data, so they never depend on files on disk (an image that
    fails to load once, e.g. while the theme is being overwritten, stays
    missing until the app restarts)."""
    import base64
    tmpl = open(os.path.join(ROOT, "tools", "toggles.template.css")).read()
    tmpl = re.sub(r"\A/\*.*?\*/\n", "", tmpl, flags=re.S)        # drop the template's header
    def embed(m):
        path = os.path.join(ROOT, "gtk-4.0", folder, m.group(1))
        data = base64.b64encode(open(path, "rb").read()).decode()
        return 'url("data:image/png;base64,%s")' % data
    return re.sub(r'url\("assets/([^"]+\.png)"\)', embed, tmpl)


def write_toggles(css_path, folder):
    s = open(css_path).read()
    s, n = TOGGLES_RE.subn(lambda m: m.group(1) + toggles_css(folder) + m.group(2), s)
    assert n == 1, css_path
    open(css_path, "w").write(s)


def main():
    build_assets("gtk-4.0")
    build_assets("gtk-3.0")
    write_toggles(os.path.join(ROOT, "gtk-4.0", "gtk.css"), "assets")   # light block
    build_gtk4()                                                          # copies gtk.css
    write_toggles(os.path.join(ROOT, "gtk-4.0", "gtk-dark.css"), "assets/dark")
    build_gtk3()
    for f in ("toggles.css", "toggles-dark.css"):                         # old layout
        if os.path.exists(os.path.join(ROOT, "gtk-4.0", f)):
            os.remove(os.path.join(ROOT, "gtk-4.0", f))
    print("built gtk-4.0/gtk-dark.css, gtk-3.0/gtk-dark.css and assets/dark/")


if __name__ == "__main__":
    main()
